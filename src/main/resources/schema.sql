DROP TABLE IF EXISTS "user";
DROP TABLE IF EXISTS item;
DROP TABLE IF EXISTS booking;
DROP TABLE IF EXISTS request;


-- Создаем таблицу пользователей
CREATE TABLE "user" (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE item_request (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    description TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    requestor_id BIGINT NOT NULL,
    CONSTRAINT fk_requests_requestor
        FOREIGN KEY (requestor_id) REFERENCES "user"(id)
);

CREATE TABLE item (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    owner_id BIGINT NOT NULL,
    request_id BIGINT NULL, -- Может быть NULL, если вещь создана не по запросу
    CONSTRAINT fk_items_owner FOREIGN KEY (owner_id) REFERENCES "user"(id), -- Ссылка на таблицу пользователей
    CONSTRAINT fk_items_request FOREIGN KEY (request_id) REFERENCES item_request(id) -- Ссылка на таблицу запросов
);

CREATE TABLE booking (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    start_at DATETIME NOT NULL,
    end_at DATETIME NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    item_id BIGINT NOT NULL,
    booker_id BIGINT NOT NULL,

    CONSTRAINT fk_bookings_item
        FOREIGN KEY (item_id) REFERENCES item(id),

    CONSTRAINT fk_bookings_booker
        FOREIGN KEY (booker_id) REFERENCES "user"(id),

    CONSTRAINT chk_dates CHECK (start_at < end_at)
);
